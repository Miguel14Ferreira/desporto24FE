function normalized(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase().replace(/\s+/g, ' ');
}
const byNormalised = (values: Readonly<Record<string, string>>): Readonly<Record<string, string>> =>
  Object.fromEntries(Object.entries(values).map(([source, translation]) => [normalized(source), translation]));

const EN_LABELS: Readonly<Record<VenueCatalogueLabelKind, Readonly<Record<string, string>>>> = {
  sport: byNormalised(EN_SPORTS),
  venueType: byNormalised(EN_VENUE_TYPES),
  surface: byNormalised(EN_SURFACES)
};

export function venueCatalogueDisplayLabel(
  value: string | null | undefined,
  kind: VenueCatalogueLabelKind,
  language: 'pt' | 'en' = typeof localStorage !== 'undefined' && localStorage.getItem('d24-language') === 'en'
    ? 'en' : 'pt'
): string {
  if (!value) return '';
  if (language !== 'en') return value;
  return EN_LABELS[kind][normalized(value)] ?? value;
}
